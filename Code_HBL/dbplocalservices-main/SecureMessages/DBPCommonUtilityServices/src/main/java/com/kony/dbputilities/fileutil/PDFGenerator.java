    private void addCombinedStatementRow(Table transTable, JsonObject rowData,String[] fields) throws Exception {
        try {
            for (int i = 0; i < fields.length; i++) {
                if (rowData.has(fields[i]) && StringUtils.isNotBlank(rowData.get(fields[i]).getAsString())) {
                    String data = rowData.get(fields[i]).getAsString();
                    if ("transactionDate".equals(fields[i])) {
                        data = HelperMethods.convertDateFormat(data, "MM/dd/yyyy");
                    }
                    if ("amount".equals(fields[i])) {
                        data = this.currencyCode + data;
                    }
                    if ("fromAccountBalance".equals(fields[i])) {
                        data = this.currencyCode + data;
                    }
                    if ("transactionDate".equals(fields[i])) {
                    	transTable.addCell(getCombinedStatmentCell().add(new Paragraph(data).setFontColor(ColorConstants.BLACK, 0.9f)));
                    } else {
                    	transTable.addCell(getCombinedStatmentCell().add(new Paragraph(data)));
                    }
                } else {
                    transTable.addCell(getNoBorderCell().setBorderBottom(new SolidBorder(ColorConstants.LIGHT_GRAY, 0.8f, 0.6f)).setHeight(20f));
                }
            }
            transTable.setMarginLeft(3f);
        } catch (Exception e) {
            alert.prepareError("Error in generation of pdf",e).log();
            throw e;
        }
    }
    
