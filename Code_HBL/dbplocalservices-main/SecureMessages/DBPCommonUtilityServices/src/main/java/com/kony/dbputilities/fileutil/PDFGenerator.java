    private void addTransactionsData(JsonArray data, Table transTable) {
        if (null != data && data.size() > 0) {
            for (int i = data.size() - 1; i >= 0; i--) {
                JsonObject rowData = data.get(i).getAsJsonObject();

                addRow(transTable, rowData,this.fields);
                String amount = rowData.get("amount").getAsString();
                if (!amount.startsWith("-")) {
                    transTable.addCell(getNoBorderCell());
                    transTable.addCell(getNoBorderCell().add(new Paragraph(amount)));
                } else {
                    transTable.addCell(getNoBorderCell().add(new Paragraph(amount)));
                    transTable.addCell(getNoBorderCell());
                }
                if (rowData.has("fromAccountBalance")) {
                    transTable.addCell(
                            getNoBorderCell().add(new Paragraph(rowData.get("fromAccountBalance").getAsString())));
                }
            }
        }
    }

    private void addRow(Table transTable, JsonObject rowData,String[] fields) {
        try {
            for (int i = 0; i < fields.length; i++) {
                if (rowData.has(fields[i])) {
                    String data = rowData.get(fields[i]).getAsString();
                    if ("transactionDate".equals(fields[i])) {
                        data = HelperMethods.convertDateFormat(data, "MM/dd/yyyy");
                    }
                    if ("Date".equals(fields[i])) {
                        data = HelperMethods.convertDateFormat(data, this.paymentDateFormat);
                    }
                    transTable.addCell(getNoBorderCell().add(new Paragraph(data)));
                } else {
                    transTable.addCell(getNoBorderCell());
                }
            }
        } catch (Exception e) {
            alert.prepareError("Error in generation of pdf",e).log();
        }
    }
