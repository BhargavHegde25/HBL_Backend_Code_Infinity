CREATE DEFINER=`infinitydb`@`%` PROCEDURE `useraccounts_create_proc`(
IN _userId VARCHAR(50) CHARACTER SET UTF8 COLLATE utf8_general_ci, 
IN _accountsCSV TEXT CHARACTER SET UTF8 COLLATE utf8_general_ci, 
IN _coreCustomerId VARCHAR(50) CHARACTER SET UTF8 COLLATE utf8_general_ci,
IN _contractId VARCHAR(50) CHARACTER SET UTF8 COLLATE utf8_general_ci,
IN _legalEntityId VARCHAR(50) CHARACTER SET UTF8 COLLATE utf8_general_ci,
IN _defaultAccount VARCHAR(50) CHARACTER SET UTF8 COLLATE utf8_general_ci  -- New input parameter
) 
BEGIN 
DECLARE accountID varchar(255) ;
DECLARE finished INTEGER DEFAULT 0 ;
DECLARE favouriteStatusValue INTEGER DEFAULT 0;  -- Variable to hold favourite status
DECLARE accountData CURSOR FOR (SELECT contractaccounts.accountId FROM contractaccounts WHERE contractId = _contractId
        AND coreCustomerId = _coreCustomerId AND find_in_set(contractaccounts.accountId,_accountsCSV) AND companyLegalUnit = _legalEntityId);
DECLARE CONTINUE HANDLER FOR NOT FOUND SET finished = 1;
OPEN accountData; 
getAccount : LOOP
fetch accountData into accountID; 
     IF finished = 1 THEN 
	     LEAVE getAccount;
	 ELSE
		-- Set favourite status: 1 if accountID matches accountNumber, otherwise 0
         IF accountID = _defaultAccount THEN
             SET favouriteStatusValue = 1;
         ELSE
             SET favouriteStatusValue = 0;
         END IF;
         SET @id = (SELECT LEFT(UUID(), 50));
         set @accounttypeid = (select contractaccounts.typeId from contractaccounts where contractaccounts.accountId =accountID);
         set @accounttypename = (select accounttype.TypeDescription from accounttype where accounttype.TypeID =@accounttypeid);
		INSERT INTO `customeraccounts` (`id`, `Customer_id`, `Account_id`,`contractId`, `coreCustomerId`, `companyLegalUnit`, `accountType`, `FavouriteStatus`)
            VALUES (@id, _userId, accountID, _contractId, _coreCustomerId, _legalEntityId, @accounttypename, favouriteStatusValue);
      END IF;
      ITERATE  getAccount;
END LOOP getAccount;
CLOSE accountData;
END
